// Aliases: normalized variant -> canonical key in T
const ALIASES = {
  'bengal gram': 'gram',
  'groundnut seed': 'groundnut',
  'onion green': 'onion',
  'ladies finger': 'bhindi',
  'chilly capsicum': 'capsicum',
  cucumber: 'cucumbar',
  radish: 'raddish',
  watermelon: 'water melon',
  chillies: 'dry chillies',
  til: 'sesamum',
  sesame: 'sesamum',
  castor: 'castor seed',
}

export function normalizeCommodityKey(name = '') {
  return name
    .replace(/\(.*?\)/g, ' ')
    .replace(/[^a-zA-Z ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
}

export function translateCommodity(name, lang) {
  if (!name) return name
  if (!lang || lang === 'en') return name
  const key = normalizeCommodityKey(name)
  const canonical = ALIASES[key] || key
  return T[canonical]?.[lang] || name
}
